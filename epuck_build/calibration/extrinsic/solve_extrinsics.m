function field = solve_extrinsics(fit, intrinsic)
assert(size(fit.world,1)>=4 && size(unique(fit.world,'rows'),1)==size(fit.world,1) ...
    && size(unique(fit.pixel,'rows'),1)==size(fit.pixel,1) ...
    && rank(fit.world-mean(fit.world,1))==2 && rank(fit.pixel-mean(fit.pixel,1))==2, ...
    'epuck:DegeneratePoints','需要至少四个不同的非共线对应点，并应覆盖场地。');
calibrated = intrinsic.cameraParams.Intrinsics;
idealPixels = undistortPoints(fit.pixel,calibrated);
idealIntrinsics = cameraIntrinsics(calibrated.FocalLength,calibrated.PrincipalPoint, ...
    calibrated.ImageSize);
pose = estimateExtrinsics(idealPixels,fit.world,idealIntrinsics);
field = struct('kind',"field",'K',intrinsic.K,'R',pose.R,'t',pose.Translation(:));
center = -field.R.'*field.t;
assert(all(isfinite(center)) && center(3)>0,'epuck:BadExtrinsics', ...
    '相机中心未位于地面上方。检查标定点对应关系及坐标轴是否为右手系。');
end
