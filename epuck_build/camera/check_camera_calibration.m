function check_camera_calibration(cfg, focus, intrinsic)
assert(cfg.name == intrinsic.camera.name && cfg.index == intrinsic.camera.index ...
    && cfg.resolution == intrinsic.camera.resolution, ...
    'epuck:CameraChanged','设备或分辨率与内参不匹配，请重新标定。');
assert(focus_matches(focus,intrinsic.focus) && focus.locked == intrinsic.focus.locked, ...
    'epuck:FocusChanged','对焦设置与内参不匹配，请重新标定。');
end
